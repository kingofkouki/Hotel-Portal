$ErrorActionPreference = "Stop"

$projectRoot = Split-Path -Parent $PSScriptRoot
$html = [System.IO.File]::ReadAllText((Join-Path $projectRoot "index.html"))
$styles = [System.IO.File]::ReadAllText((Join-Path $projectRoot "css\style.css"))

$styleLink = '<link rel="stylesheet" href="css/style.css">'
if (-not $html.Contains($styleLink)) {
    throw "Could not find the stylesheet link in index.html."
}
$html = $html.Replace($styleLink, "<style>`n$styles`n</style>")

$templateMarker = "<!-- Apps Script module templates are generated by apps-script/BuildPortal.ps1. -->"
if (-not $html.Contains($templateMarker)) {
    throw "Could not find the module template marker in index.html."
}

$templates = [System.Text.StringBuilder]::new()
Get-ChildItem -Path (Join-Path $projectRoot "modules") -Filter "*.html" |
    Sort-Object Name |
    ForEach-Object {
        $moduleName = [System.IO.Path]::GetFileNameWithoutExtension($_.Name)
        $moduleHtml = [System.IO.File]::ReadAllText($_.FullName)
        [void]$templates.AppendLine("<template id=`"module-$moduleName`">")
        [void]$templates.AppendLine($moduleHtml)
        [void]$templates.AppendLine("</template>")
    }
$html = $html.Replace($templateMarker, $templates.ToString())

$scriptFiles = @(
    "app.js",
    "modul.js",
    "dashboard.js",
    "settings.js",
    "room-status.js"
)
foreach ($scriptName in $scriptFiles) {
    $scriptTag = '<script src="js/' + $scriptName + '"></script>'
    if (-not $html.Contains($scriptTag)) {
        throw "Could not find script reference: $scriptTag"
    }
    $script = [System.IO.File]::ReadAllText((Join-Path $projectRoot ("js\" + $scriptName)))
    $inlineScript = "<script>`n$script`n</script>"
    $html = $html.Replace($scriptTag, $inlineScript)
}

$outputPath = Join-Path $PSScriptRoot "Portal.html"
$utf8NoBom = [System.Text.UTF8Encoding]::new($false)
[System.IO.File]::WriteAllText($outputPath, $html, $utf8NoBom)
Write-Output "Generated $outputPath"
